"""Cross-check CNF truth under manually selected source matchings, against independent cube statistics.
This evaluates the actual gate assignments generated by frozen V12 CNF code.
"""
import importlib.util,sys,random
from itertools import combinations
from pathlib import Path
q=Path(__file__).resolve().parents[1] / 'v12_certificates' / 'verification'
sys.path.insert(0,str(q))
from rebuild_cnf import build,CASES,PAIRS
N=128

def update(x,i,b): return (x & ~(1<<i)) | (b<<i)
def independent(pair_set):
  E=set(); F=[]
  for x,y in pair_set:
    for i in range(7):
      for b in range(2): E.add(tuple(sorted((update(x,i,b), update(y,i,b)))))
  C={x for p in pair_set for x in p}; a=len(pair_set)
  e=sum(((v^w).bit_count()==1) for v,w in combinations(sorted(C),2))
  d=14*a-len(E)
  xi=sum(max(sum((y^(1<<i)) in C for i in range(7))-1,0) for y in range(N) if y not in C)
  return e-d,xi,C

rng=random.Random(20261012)
cases=[]
for kind in ('B.antipodal','B.mixed','A.normal','A.special','A.antipodal'):
  antipodal=kind=='B.antipodal'
  eligible=[p for p in PAIRS if (p[0]^p[1]).bit_count()==7] if antipodal else PAIRS
  # Sample both legal and illegal endpoint-disjointness cases.
  for size in (1,2,3):
    selected=[]
    for p in rng.sample(eligible,len(eligible)):
      if not set(p)&set(v for e in selected for v in e):selected.append(p)
      if len(selected)==size:break
    if len(selected)<size:continue
    ed,xi,C=independent(selected)
    expected=(xi==0) if kind.startswith('B.') else (ed==0 and xi<=2)
    formula=build(kind,k=size,chosen=set(selected),fixed_override=[])
    found=formula.check_assignment()
    if found != expected:
      raise AssertionError((kind,size,selected,ed,xi,found,expected))
    cases.append((kind,size,ed,xi,found))
    print('PASS',kind,'source pairs',size,'e-D',ed,'Xi',xi,'CNF truth',found,flush=True)
print('ALL PASS: independent original constraint / frozen CNF assignment evaluations',len(cases))
